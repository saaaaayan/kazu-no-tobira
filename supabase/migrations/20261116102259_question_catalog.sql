create schema question_catalog;
revoke all on schema question_catalog from public, anon, authenticated, service_role;

create role kazu_catalog_import nologin;
create role kazu_catalog_review nologin;
grant usage on schema question_catalog to kazu_catalog_import, kazu_catalog_review;

create type question_catalog.review_status as enum ('unreviewed','needs_work','verified','ready','rejected');

create table question_catalog.islands (
  id text primary key,
  title text not null,
  name text not null,
  position integer not null unique check (position >= 0)
);
create table question_catalog.stages (
  id text primary key,
  island_id text not null references question_catalog.islands,
  title text not null,
  position integer not null check (position >= 0),
  unit text not null,
  skill text not null,
  kind text not null check (kind in ('normal','extra','secret')),
  access text not null check (access in ('free','premium','pending')),
  difficulty smallint not null check (difficulty between 1 and 3),
  unique(island_id,position)
);
create table question_catalog.banks (
  stage_id text primary key references question_catalog.stages,
  version integer not null check (version > 0),
  selection text not null check (selection in ('random','balanced')),
  source text not null check (source in ('existing','draft'))
);
create table question_catalog.questions (
  id text primary key,
  stage_id text not null references question_catalog.stages,
  stem text not null,
  format text not null,
  difficulty smallint not null check (difficulty between 1 and 3),
  has_figure boolean not null,
  search text not null,
  exact text not null,
  equivalent text,
  shape text,
  active boolean not null,
  status question_catalog.review_status not null default 'unreviewed',
  reason text,
  note text not null default '',
  version integer not null default 0 check (version >= 0),
  fingerprint text not null check (fingerprint ~ '^[a-f0-9]{64}$'),
  created_at timestamptz not null,
  updated_at timestamptz not null,
  check ((status='rejected' and reason is not null) or (status<>'rejected' and reason is null))
);
create table question_catalog.versions (
  fingerprint text primary key check (fingerprint ~ '^[a-f0-9]{64}$'),
  payload_text text not null,
  payload jsonb generated always as (payload_text::jsonb) stored,
  check (encode(sha256(convert_to(payload_text,'UTF8')),'hex') = fingerprint)
);
alter table question_catalog.questions
  add constraint question_current_version foreign key (fingerprint) references question_catalog.versions;
create table question_catalog.history (
  id bigint generated by default as identity primary key,
  question_id text not null references question_catalog.questions,
  created timestamptz not null,
  actor text not null,
  event text not null check (event in ('registered','review','revision','retired')),
  previous_status question_catalog.review_status,
  status question_catalog.review_status not null,
  note text not null,
  reason text,
  fingerprint text not null references question_catalog.versions
);
create table question_catalog.administrators (
  user_id uuid primary key references auth.users on delete cascade,
  active boolean not null default true
);

create extension if not exists pg_trgm with schema extensions;
create index questions_search on question_catalog.questions using gin (search extensions.gin_trgm_ops) where active;
create index questions_by_stage on question_catalog.questions (stage_id,status,id) where active;
create index questions_by_status on question_catalog.questions (status,stage_id,id) where active;
create index questions_by_format on question_catalog.questions (format,difficulty,stage_id,id) where active;
create index questions_exact on question_catalog.questions (md5(exact)) where active;
create index questions_equivalent on question_catalog.questions (md5(equivalent)) where active;
create index questions_shape on question_catalog.questions (md5(shape)) where active;
create index question_history_recent on question_catalog.history (question_id,id desc);
create index question_history_fingerprint on question_catalog.history (fingerprint);
create index questions_fingerprint on question_catalog.questions (fingerprint);

alter table question_catalog.islands enable row level security;
alter table question_catalog.stages enable row level security;
alter table question_catalog.banks enable row level security;
alter table question_catalog.questions enable row level security;
alter table question_catalog.versions enable row level security;
alter table question_catalog.history enable row level security;
alter table question_catalog.administrators enable row level security;

grant select, insert on question_catalog.islands, question_catalog.stages, question_catalog.banks,
  question_catalog.questions, question_catalog.versions, question_catalog.history to kazu_catalog_import;
create policy import_islands on question_catalog.islands for all to kazu_catalog_import using (true) with check (true);
create policy import_stages on question_catalog.stages for all to kazu_catalog_import using (true) with check (true);
create policy import_banks on question_catalog.banks for all to kazu_catalog_import using (true) with check (true);
create policy import_questions on question_catalog.questions for all to kazu_catalog_import using (true) with check (true);
create policy import_versions on question_catalog.versions for all to kazu_catalog_import using (true) with check (true);
create policy import_history on question_catalog.history for all to kazu_catalog_import using (true) with check (true);
grant select on all tables in schema question_catalog to kazu_catalog_review;
grant update (status,reason,note,version,updated_at) on question_catalog.questions to kazu_catalog_review;
grant insert on question_catalog.history to kazu_catalog_review;
grant usage,select on sequence question_catalog.history_id_seq to kazu_catalog_review;
create policy review_read_islands on question_catalog.islands for select to kazu_catalog_review using (true);
create policy review_read_stages on question_catalog.stages for select to kazu_catalog_review using (true);
create policy review_read_banks on question_catalog.banks for select to kazu_catalog_review using (true);
create policy review_read_questions on question_catalog.questions for select to kazu_catalog_review using (true);
create policy review_read_versions on question_catalog.versions for select to kazu_catalog_review using (true);
create policy review_read_history on question_catalog.history for select to kazu_catalog_review using (true);
create policy review_read_admins on question_catalog.administrators for select to kazu_catalog_review using (true);
create policy review_update_questions on question_catalog.questions for update to kazu_catalog_review
  using (active) with check (active);
create policy review_insert_history on question_catalog.history for insert to kazu_catalog_review
  with check (event='review' and previous_status is not null);
